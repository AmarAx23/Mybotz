function fmt(n) {
  return Math.round(n / 100) * 100 >= 0 ? (Math.round(n / 100) * 100).toLocaleString('en-US') : String(n);
}

function stepsFor(weekNumber, weekdayKey) {
  const base = WEEK_STEPS[weekNumber];
  if (weekNumber === 16) return base;
  if (weekdayKey === 'wed') return Math.max(4000, base - 1500);
  if (weekdayKey === 'sat') return base + 1500;
  if (weekdayKey === 'sun') return Math.max(3000, base - 2500);
  return base;
}

function getWalkDay(weekNumber, weekdayKey) {
  const steps = stepsFor(weekNumber, weekdayKey);
  let msg = `🎯 ชาเลนจ์วันนี้: เดินให้ได้ ${fmt(steps)} ก้าว\n`;
  msg += `⭐ โบนัส: ${DAILY_BONUS[weekdayKey]}`;
  if (weekNumber === 16) msg += '\n\nสัปดาห์ Deload: ลดความหนักลง เน้นพักฟื้นแล้วประเมินร่างกายใหม่';
  return msg;
}

module.exports = { WEEK_STEPS, PHASE_START_NOTES_F, getWalkDay, stepsFor };
